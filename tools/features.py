#!/usr/bin/env python3
"""Feature diff page: docs/features.tsv -> public/docs/FEATURES.md (generated; never hand-edited).

Section 1 lists the PS3 game's features with the port's status (works / partial / not yet / not yet verified / declined /
not applicable) and the evidence each status rests on; section 2 lists what the port adds (available now / planned).

    python3 tools/features.py            # regenerate public/docs/FEATURES.md
    python3 tools/features.py --check    # exit 1 when the page is stale, the data is malformed, a cp:NAME checkpoint
                                         # does not exist, a link leaves the public export, or an entry of
                                         # docs/completed/enhancements.md has no port row (docs-check check 7)
    python3 tools/features.py --root DIR # another repo root (the host test's fixture)

The enhancements.md entries the check expects a row for: every "## " heading except the file's own title and the
"Wanted" header, every top-level "- **Title**" bullet, and every paragraph that opens with "**Title**" (except
IGNORED_ENTRIES). A port row's detail column names its entry by a case-insensitive substring of the title; a detail
that is empty or starts with "(" is a prose item with no entry of its own.

Data format of docs/features.tsv (plain tab-separated, no comments, every row 7 cells, no straight double quotes, so
GitHub can render it as a table):

    Columns (first row is the header):
      kind     ps3  = a feature of the PS3 game (parity table)      port = a feature the PS3 version does not have
      area     grouping on the page (same text = same table)
      feature  short name
      detail   ps3 rows: what the PS3 game does                      port rows: the enhancements.md entry it comes from
               (a case-insensitive substring of that entry's title; empty = prose item with no entry of its own)
      status   ps3 rows: works | partial | not yet | unverified | declined | n/a
               port rows: available | planned
      evidence ps3 rows: where the status was recorded. cp:NAME links the checkpoint NAME from docs/checkpoints/README.md
               (plain NAME in the public tree, which has no checkpoint log);
               markdown links must point at files the public export ships (tools/features.py PUBLIC_PREFIXES).
               port rows: the default (on/off, or the planned default)
      note     ps3 rows: short public remark (optional)              port rows: the environment switch, if any, then a remark
    
    Rules: "works" only with recorded evidence (a checkpoint, a test, a dated status note); a path that exists in code
    but was never exercised is "unverified" (shown as "not yet verified"). Guesses are marked ASSUMPTION here and the
    page drops the mark's text; keep ASSUMPTION inside the note column only. Update this file when a status changes
    (a new run, test or checkpoint), then regenerate.
"""
import argparse
import io
import pathlib
import re
import sys

DATA = "docs/features.tsv"
PAGE = "public/docs/FEATURES.md"
ENH = "docs/completed/enhancements.md"
CP_README = "docs/checkpoints/README.md"
HEADER = "<!-- Generated by tools/features.py from docs/features.tsv. Do not edit by hand: edit the data and rerun. -->"
# Files the public export ships (tools/export-public.sh ALLOW); a page link anywhere else would dangle on GitHub.
PUBLIC_PREFIXES = ("docs/checkpoints/", "docs/requirements.md", "docs/BUILDING.md", "docs/HOW-IT-WORKS.md",
                   "docs/GLOSSARY.md", "docs/ROADMAP.md", "README.md", "NOTICE.md", "LICENSE",
                   ".github/CONTRIBUTING.md")
# enhancements.md paragraphs that open with a bold title but are not features.
IGNORED_ENTRIES = ("Facts from the RPCS3 wiki", "No console window",
                   "Split-screen upgrades")  # its public row waits for the gate (2026-10-22); remove once the row lands

PS3_STATUS = {"works": "works", "partial": "partial", "not yet": "not yet", "unverified": "not yet verified",
              "declined": "declined", "n/a": "not applicable"}
PS3_ORDER = ("works", "partial", "not yet", "unverified", "declined", "n/a")
PORT_STATUS = ("available", "planned")
COLUMNS = ("kind", "area", "feature", "detail", "status", "evidence", "note")


def read_rows(root):
    """Rows of the TSV as dicts, in file order, with the line number under 'line'. Raises ValueError on a bad file."""
    text = (root / DATA).read_text(encoding="utf-8")
    lines = [(i + 1, l) for i, l in enumerate(text.splitlines()) if l.strip() and not l.lstrip().startswith("#")]
    if not lines:
        raise ValueError(f"{DATA}: empty")
    head = lines[0][1].split("\t")
    if tuple(head) != COLUMNS:
        raise ValueError(f"{DATA}: header must be {' '.join(COLUMNS)}, got {' '.join(head)}")
    rows = []
    for ln, l in lines[1:]:
        if '"' in l:   # GitHub's TSV viewer reads a straight double quote as CSV quoting ("Illegal quoting")
            raise ValueError(f"{DATA}:{ln}: straight double quote; use \u201c \u201d or ' inside a field")
        cells = l.split("\t")
        if len(cells) == len(COLUMNS) - 1:   # editors strip a trailing tab: an empty note is allowed
            cells.append("")
        if len(cells) != len(COLUMNS):
            raise ValueError(f"{DATA}:{ln}: {len(cells)} columns, expected {len(COLUMNS)}")
        row = dict(zip(COLUMNS, (c.strip() for c in cells)))
        row["line"] = ln
        if row["kind"] not in ("ps3", "port"):
            raise ValueError(f"{DATA}:{ln}: kind must be ps3 or port")
        if row["kind"] == "ps3" and row["status"] not in PS3_STATUS:
            raise ValueError(f"{DATA}:{ln}: ps3 status '{row['status']}' not in {', '.join(PS3_STATUS)}")
        if row["kind"] == "port" and row["status"] not in PORT_STATUS:
            raise ValueError(f"{DATA}:{ln}: port status '{row['status']}' not in {', '.join(PORT_STATUS)}")
        if not row["feature"]:
            raise ValueError(f"{DATA}:{ln}: empty feature")
        if row["kind"] == "ps3" and row["status"] == "works" and not row["evidence"]:
            raise ValueError(f"{DATA}:{ln}: 'works' needs evidence")
        rows.append(row)
    return rows


def checkpoints(root):
    """name -> png path (relative to the repo root) from the checkpoint log's table; None when the log is absent
    (the public tree: the export ships no checkpoints, so cp:NAME renders as the plain name)."""
    p = root / CP_README
    if not p.exists():
        return None
    return {m.group(1): "docs/checkpoints/" + m.group(2)
            for m in re.finditer(r"\| \[([^\]]+)\]\(([^)]+\.png)\) \|", p.read_text(encoding="utf-8"))}


def enhancement_entries(root):
    """Titles of the enhancements.md entries a port row must cover (see the module docstring)."""
    p = root / ENH
    if not p.exists():
        return []
    titles = []
    prev_blank = True
    for l in p.read_text(encoding="utf-8").splitlines():
        m = re.match(r"## (.+)", l)
        if m:
            t = m.group(1).strip()
            if not t.lower().startswith(("enhancements", "wanted")):
                titles.append(t)
        elif (m := re.match(r"- \*\*(.+?)\*\*", l)):
            titles.append(m.group(1).strip())
        elif prev_blank and (m := re.match(r"\*\*(.+?)\*\*", l)):
            titles.append(m.group(1).strip())
        prev_blank = not l.strip()
    return [t for t in titles if not any(t.startswith(i) for i in IGNORED_ENTRIES)]


def cell(s):
    return s.replace("|", "\\|")


def render_evidence(text, cps, problems, line):
    """Replace cp:NAME tokens by links to the checkpoint PNGs; record unknown names and non-public links.
    cps None (public tree, no checkpoint log): cp:NAME becomes the plain NAME, which is what the export's
    drop_checkpoints leaves of the private page's checkpoint links, so both trees generate the same page."""
    def cp(m):
        name = m.group(1)
        if cps is None:
            return name
        if name not in cps:
            problems.append(f"{DATA}:{line}: unknown checkpoint cp:{name}")
            return name
        return f"[{name}]({cps[name]})"
    out = re.sub(r"cp:([\w.-]+)", cp, text)
    for m in re.finditer(r"\]\(([^)\s]+)\)", out):
        t = m.group(1)
        if re.match(r"(https?:|mailto:|#)", t):
            continue
        if not t.startswith(PUBLIC_PREFIXES):
            problems.append(f"{DATA}:{line}: link {t} is not in the public export")
    # The data's links are written from the repository root; the page lives in docs/ (fewer files
    # at the top level), so docs/X becomes X and anything else at the root goes up one level.
    def rel(m):
        t = m.group(1)
        if re.match(r"(https?:|mailto:|#)", t):
            return m.group(0)
        return "](" + (t[5:] if t.startswith("docs/") else "../" + t) + ")"
    return re.sub(r"\]\(([^)\s]+)\)", rel, out)


# Estimated parity (a rough tracker, not a measurement): each PS3 feature that applies scores its status weight;
# declined and not-applicable rows are left out.
PARITY_WEIGHT = {"works": 1.0, "partial": 0.5, "unverified": 0.25, "not yet": 0.0}
PARITY_RULE = ("an estimate: works counts 1, partial 1/2, not yet verified 1/4, not yet 0; declined and not-applicable "
               "features are left out")


def parity(rows):
    rs = [r for r in rows if r["status"] in PARITY_WEIGHT]
    return round(100 * sum(PARITY_WEIGHT[r["status"]] for r in rs) / len(rs)) if rs else 0


def render(rows, cps, problems):
    ps3 = [r for r in rows if r["kind"] == "ps3"]
    port = [r for r in rows if r["kind"] == "port"]
    counts = {s: sum(1 for r in ps3 if r["status"] == s) for s in PS3_ORDER}
    pcounts = {s: sum(1 for r in port if r["status"] == s) for s in PORT_STATUS}
    o = io.StringIO()
    w = o.write
    w(HEADER + "\n")
    w("# Features: the PS3 game and the port\n\n")
    w("What the PS3 version of Killzone 3 does and how far the port reproduces it (section 1), and what the port adds "
      "that the PS3 version does not have (section 2). Every status comes from a recorded result in this repository: "
      "a screenshot checkpoint, a test, or a dated status note. *Not yet verified* means the code path exists but "
      "nothing has exercised it; *works* is only claimed with evidence.\n\n")
    w("| Status | Meaning | Count |\n|---|---|---|\n")
    meaning = {"works": "verified in a run", "partial": "runs, with known gaps", "not yet": "not reached or not started",
               "unverified": "present in code, never exercised", "declined": "will not be done",
               "n/a": "has no equivalent on PC"}
    for s in PS3_ORDER:
        w(f"| {PS3_STATUS[s]} | {meaning[s]} | {counts[s]} |\n")
    w(f"\nPort-only features: {pcounts['available']} available now, {pcounts['planned']} planned.\n\n")
    w(f"**Estimated parity with the PS3 version: {parity(ps3)} %** ({PARITY_RULE}).\n\n")
    w("| Area | Estimated parity | Features |\n|---|---|---|\n")
    seen = []
    for r in ps3:
        if r["area"] not in seen:
            seen.append(r["area"])
    for a in seen:
        rs = [r for r in ps3 if r["area"] == a]
        n = sum(1 for r in rs if r["status"] in PARITY_WEIGHT)
        w(f"| {a} | {f'{parity(rs)} %' if n else '-'} | {n} |\n")
    w("\n")

    w("## 1. Feature parity with the PS3 version\n\n")
    areas = []
    for r in ps3:
        if r["area"] not in areas:
            areas.append(r["area"])
    for a in areas:
        w(f"### {a}\n\n| Feature | On the PS3 | In the port | Evidence |\n|---|---|---|---|\n")
        for r in (x for x in ps3 if x["area"] == a):
            ev = render_evidence(r["evidence"], cps, problems, r["line"])
            note = f": {cell(r['note'])}" if r["note"] else ""
            w(f"| {cell(r['feature'])} | {cell(r['detail'])} | **{PS3_STATUS[r['status']]}**{note} | {cell(ev)} |\n")
        w("\n")

    w("## 2. Features the PS3 version does not have\n\n")
    w("Non-original features are opt-in where they change gameplay; display and input improvements may be on by "
      "default. Each is marked `ENHANCEMENT:` in the source. The switch "
      "column names the environment variable that controls the feature where one exists (the settings page will "
      "expose them).\n\n")
    for s, title in (("available", "Available now"), ("planned", "Planned")):
        w(f"### {title}\n\n| Feature | State | Default | Switch, notes |\n|---|---|---|---|\n")
        for r in (x for x in port if x["status"] == s):
            note = render_evidence(r["note"], cps, problems, r["line"])
            w(f"| {cell(r['feature'])} | {s} | {cell(r['evidence'])} | {cell(note)} |\n")
        w("\n")
    w("Progress and the order of the planned items: [ROADMAP.md](ROADMAP.md).\n")
    return o.getvalue(), counts, pcounts


def check_entries(rows, entries):
    """Problems: enhancements.md entries without a port row, and port rows naming an entry that does not exist."""
    problems = []
    keys = [(r["detail"], r["line"]) for r in rows
            if r["kind"] == "port" and r["detail"] and not r["detail"].startswith("(")]
    for t in entries:
        if not any(k.lower() in t.lower() for k, _ in keys):
            problems.append(f"{ENH} entry '{t}' has no port row in {DATA} (add one, or add its title to IGNORED_ENTRIES)")
    for k, ln in keys:
        if not any(k.lower() in t.lower() for t in entries):
            problems.append(f"{DATA}:{ln}: detail '{k}' matches no {ENH} entry")
    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="verify instead of writing; exit 1 on any problem")
    ap.add_argument("--root", default=str(pathlib.Path(__file__).resolve().parents[1]), help="repo root")
    ap.add_argument("-q", action="store_true", help="print only problems")
    a = ap.parse_args(argv)
    root = pathlib.Path(a.root)
    problems = []
    try:
        rows = read_rows(root)
    except (ValueError, OSError) as e:
        print(f"features: {e}", file=sys.stderr)
        return 1
    page, counts, pcounts = render(rows, checkpoints(root), problems)
    if (root / ENH).exists():
        problems += check_entries(rows, enhancement_entries(root))
    # In the public tree the page sits at docs/ (the export copies public/ to the root) and enhancements.md is absent.
    out = root / PAGE
    if not (root / "public").is_dir() and (root / "docs" / "FEATURES.md").exists():
        out = root / "docs" / "FEATURES.md"
    if a.check:
        if not out.exists():
            problems.append(f"{PAGE} missing (run tools/features.py)")
        elif out.read_text(encoding="utf-8") != page:
            problems.append(f"{PAGE} is stale (run tools/features.py)")
    if problems:
        print("features: problems:", file=sys.stderr)
        for p in problems:
            print("  - " + p, file=sys.stderr)
        return 1
    if not a.check:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(page, encoding="utf-8")
    if not a.q:
        summary = ", ".join(f"{PS3_STATUS[s]} {counts[s]}" for s in PS3_ORDER)
        print(f"features: {'OK' if a.check else PAGE} ({summary}; parity ~{parity([r for r in rows if r['kind'] == 'ps3'])} %; port-only available {pcounts['available']}, "
              f"planned {pcounts['planned']})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
