def lint(page):
    """Problems with what the page would load: scripts, and resources from anywhere but itself and Google Fonts."""
    problems = []
    if re.search(r"<script\b|\bon\w+\s*=|javascript:", page, re.I):
        problems.append("page contains a script or an event handler")
    for m in re.finditer(r"<(link|img|iframe|source|video|audio|embed|object)\b[^>]*?\b(?:href|src)=\"([^\"]+)\"", page, re.I):
        tag, url = m.group(1).lower(), m.group(2)
        if re.match(r"[a-z]+:|//", url, re.I) and not ALLOWED_EXTERNAL.match(url):
            problems.append(f"<{tag}> loads {url} (only the page itself and Google Fonts are allowed)")
    if re.search(r"/home/|file:", page):
        problems.append("page contains a local path")
    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="verify instead of writing; exit 1 on any problem")
    ap.add_argument("--root", default=str(pathlib.Path(__file__).resolve().parents[2]), help="repo root")
    ap.add_argument("--feed", help="Discussions snapshot (JSON from discussions_feed.py); missing file = static page")
    ap.add_argument("--out", help="write the page here instead of the committed path (needed with --feed)")
    ap.add_argument("-q", action="store_true", help="print only problems")
    a = ap.parse_args(argv)
    root = pathlib.Path(a.root)
    problems = []
    try:
        page = render(root, problems, discussions_feed.load(a.feed) if a.feed else ())
    except (ValueError, OSError) as e:
        print(f"website: {e}", file=sys.stderr)
        return 1
    problems += lint(page)
    out = root / PAGE
    if not (root / "public").is_dir() and (root / "site").is_dir():   # the public tree: public/site/ is site/ there
        out = root / "site" / pathlib.Path(PAGE).name
    if a.feed and not a.out:
        print("website: --feed needs --out (the committed page is always the static one)", file=sys.stderr)
        return 1
    if a.out:
        out = pathlib.Path(a.out)
    if a.check:
        if not out.exists():
            problems.append(f"{PAGE} missing (run tools/release/website.py)")
        elif out.read_text(encoding="utf-8") != page:
            problems.append(f"{PAGE} is stale (run tools/release/website.py)")
        if not (out.parent / "style.css").exists():
            problems.append(f"{out.parent.relative_to(root)}/style.css missing")
    if problems:
        print("website: problems:", file=sys.stderr)
        for p in problems:
            print("  - " + p, file=sys.stderr)
        return 1
    if not a.check:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(page, encoding="utf-8")
    if not a.q:
        print(f"website: {'OK' if a.check else PAGE} ({len(page)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
