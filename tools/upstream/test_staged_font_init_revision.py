#!/usr/bin/env python3
"""Focused test for the staged PR docs/upstream/submission/2060-cellfont-initialize-with-revision.diff.

Titles built with a newer SDK start the font library with cellFontInitializeWithRevision (NID 0xF03DCC29). Upstream
master has no such function, so the HLE table (generated by tools/gen_hle_nids.py from the library sources) has no
entry and the import is faked as CELL_OK without initialising: every later cellFont call fails with UNINITIALIZED.
Checks, on upstream master (OLD_TREE) and on a copy with the diff applied:
  1. gen_hle_nids.scan(libs/font/cellFont.c) lists NID 0xF03DCC29;
  2. cellFont.c compiled with stub guest memory: cellFontInitializeWithRevision(rev, NULL) returns CELL_OK and the
     next cellFontOpenFontset does not return CELL_FONT_ERROR_UNINITIALIZED.
Negative control: the new function with its cellFontInit call removed (what a stub that only returns OK does) fails 2.
Needs cc. Prints one PASS/FAIL line."""
import os, re, sys, tempfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _extract as X, _staged

HARNESS = r'''
#include <stdint.h>
#include <stdio.h>
#include <string.h>
uint8_t* vm_base; uint32_t ppu_vm_size; uint32_t g_ww_lo, g_ww_hi; int g_resv_store_active;
void ppu_resv_break_store(uint64_t a) { (void)a; }
void ps3_ww_report_inline(uint32_t a, uint64_t v, int n) { (void)a; (void)v; (void)n; }
int spu_coh_is_reserved(uint32_t a) { (void)a; return 0; }
void spu_coh_notify_write(uint32_t a) { (void)a; }
void spu_lockline_lock(void) {}
void spu_lockline_unlock(void) {}
#include "%(src)s"
int main(void) {
    static uint8_t mem[0x100000]; vm_base = mem; ppu_vm_size = sizeof mem;
    uint8_t* ft = mem + 0x1000;                 /* CellFontType, big-endian 0 */
    uint8_t* font = mem + 0x2000;
    s32 rc = cellFontInitializeWithRevision(0x0000000000000001ull, 0);
    s32 rc2 = cellFontOpenFontset(0, (CellFontType*)(uintptr_t)0x1000, (CellFont*)(uintptr_t)0x2000);
    (void)ft; (void)font;
    printf("%%d %%d\n", rc == CELL_OK, rc2 != CELL_FONT_ERROR_UNINITIALIZED);
    return 0;
}
'''

def scan_has_nid(tree):
    sys.path.insert(0, os.path.join(tree, "tools"))
    try:
        sys.modules.pop("gen_hle_nids", None); sys.modules.pop("nid_database", None)
        import gen_hle_nids
        return any(nid == 0xF03DCC29 for nid, _ in gen_hle_nids.scan(os.path.join(tree, "libs/font/cellFont.c")))
    finally:
        sys.path.pop(0)

def runs_ok(tree, strip_init=False):
    src = open(os.path.join(tree, "libs/font/cellFont.c")).read()
    with tempfile.TemporaryDirectory() as d:
        if strip_init:
            src2 = re.sub(r"(cellFontInitializeWithRevision\([^)]*\)\s*\{[^}]*?)return cellFontInit\(config\);",
                          r"\1return CELL_OK;", src)
            if src2 == src: sys.exit("FAIL: negative control did not apply")
            src = src2
        p = f"{d}/cellFont.c"; open(p, "w").write(src)
        code = HARNESS % {"src": p}
        failed, out = X.build_run(code, flags=["-I", os.path.join(tree, "libs/font"), "-I", tree, "-I", os.path.join(tree, "include"),
                                              "-I", os.path.join(tree, "libs")])
        return (not failed) and out.strip().splitlines()[-1:] == ["1 1"]

old, new = _staged.trees("2060-cellfont-initialize-with-revision.diff")
old_bad = not scan_has_nid(old) and not runs_ok(old)
new_ok = scan_has_nid(new) and runs_ok(new)
ctl_bad = not runs_ok(new, strip_init=True)
X.verdict("2060 cellFontInitializeWithRevision initialises the font library", old_bad, new_ok, ctl_bad)
