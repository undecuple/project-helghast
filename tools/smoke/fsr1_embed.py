#!/usr/bin/env python3
"""Generate libs/video/fsr1/fsr1_embed.h: the text of the two vendored FSR 1 headers as C string arrays, so the
D3D12 backend can compile them with D3DCompile without a file at run time or an include handler.

  fsr1_embed.py DIR            write DIR/fsr1_embed.h from DIR/ffx_a.h and DIR/ffx_fsr1.h
  fsr1_embed.py --check DIR    exit 1 when DIR/fsr1_embed.h is not exactly what the headers generate
"""
import sys, os

def lit(line):
    out = []
    for ch in line:
        o = ord(ch)
        if ch == '\\': out.append('\\\\')
        elif ch == '"': out.append('\\"')
        elif ch == '?': out.append('\\?')          # no trigraphs under -std=c99
        elif ch == '\t': out.append('\\t')
        elif o < 32 or o > 126: out.append('\\%03o' % o)
        else: out.append(ch)
    return '"' + ''.join(out) + '"'

def gen(d):
    s = ['/* Generated by tools/smoke/fsr1_embed.py from ffx_a.h and ffx_fsr1.h (AMD FidelityFX FSR 1, MIT, see LICENSE.txt);',
         ' * do not edit. One string per source line, no newline in it; rsx_upscale_fsr1.c joins them with \\n. */']
    for sym, name in (('ffx_a', 'ffx_a.h'), ('ffx_fsr1', 'ffx_fsr1.h')):
        data = open(os.path.join(d, name), 'rb').read().decode('ascii')
        lines = data.split('\n')
        if lines and lines[-1] == '': lines.pop()
        s.append('static const char* const rsx_fsr1_%s_lines[] = {' % sym)
        s += ['  ' + lit(l.rstrip('\r')) + ',' for l in lines]
        s.append('};')
    return '\n'.join(s) + '\n'

if __name__ == '__main__':
    a = sys.argv[1:]
    chk = a and a[0] == '--check'
    if chk: a = a[1:]
    if len(a) != 1: sys.exit(__doc__)
    want = gen(a[0]); p = os.path.join(a[0], 'fsr1_embed.h')
    if chk:
        have = open(p).read() if os.path.exists(p) else None
        sys.exit(0 if have == want else 1)
    open(p, 'w', newline='\n').write(want)
